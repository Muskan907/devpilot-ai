"""Google ADK LLM-as-Judge Agent.

Scores a finished run against a fixed rubric (1-5 per criterion, with justification).
It complements - never replaces - the objective pytest verdict: tests decide pass/fail,
the judge rates what tests cannot measure (plan quality, code quality, test adequacy,
diagnosis quality). A different model from the generator is used by default
(settings.JUDGE_MODEL) to reduce self-preference bias [Zheng et al., 2023].
"""

import difflib
from typing import Any, Dict, Optional

from google.adk.agents import LlmAgent

from config.settings import settings
from core.blackboard import global_blackboard
from core.schemas.judge import JudgeVerdict
from agents.google_adk.adk_runtime import ADKInvoker, parse_json_model, resolve_adk_model

JUDGE_INSTRUCTION = (
    "You are an impartial senior code reviewer acting as an evaluation judge. Score each "
    "criterion from 1 (very poor) to 5 (excellent) using only the evidence provided. Be strict: "
    "5 means no meaningful improvement is possible. Do not reward length. Each justification must "
    "cite concrete evidence (a criterion, a line of code, a missing edge case)."
)

RUBRIC = """Rubric:
- plan_quality: acceptance criteria are complete, specific, testable and faithful to the requirement.
- code_correctness: the implementation satisfies the requirement, including stated edge cases/errors.
- code_quality: the change is minimal, readable and consistent with the existing code style.
- test_adequacy: generated tests verify every acceptance criterion and the edge cases.
- diagnosis_quality (ONLY if failure diagnoses are provided, else null): root cause correct and actionable.
Return a single JSON object in a ```json block:
{"plan_quality": {"score": n, "justification": "..."}, "code_correctness": {...},
 "code_quality": {...}, "test_adequacy": {...}, "diagnosis_quality": {...} or null}"""


class GoogleADKJudgeAgent:
    """Scores agent outputs with a rubric (LLM-as-Judge)."""

    def __init__(self, model_name: Optional[str] = None):
        self.agent_id = "GoogleADK:JudgeAgent"
        self.framework = "google_adk"
        self.model_name = model_name or settings.JUDGE_MODEL
        self.adk_agent = LlmAgent(
            name="google_adk_judge",
            description="LLM-as-Judge evaluator for multi-agent software engineering runs",
            instruction=JUDGE_INSTRUCTION,
            model=resolve_adk_model(self.model_name),
        )
        self.invoker = ADKInvoker(self.adk_agent, self.agent_id)

    @staticmethod
    def collect_evidence() -> Dict[str, Any]:
        """Gathers the run's artefacts from the Blackboard."""
        state = global_blackboard.state
        diffs, tests = [], []
        for path, patch in state.active_patches.items():
            diff = "".join(difflib.unified_diff(
                (patch.original_content or "").splitlines(keepends=True),
                (patch.modified_content or "").splitlines(keepends=True),
                fromfile=f"a/{path}", tofile=f"b/{path}",
            ))
            (tests if "test" in path.lower() else diffs).append(diff or f"(new file {path})\n{patch.modified_content}")
        report = state.test_reports[-1] if state.test_reports else None
        return {
            "requirement": state.requirement.raw_prompt if state.requirement else "",
            "acceptance_criteria": [
                f"{ac.id}: {ac.description}" for ac in (state.analysis.acceptance_criteria if state.analysis else [])
            ],
            "code_diff": "\n".join(diffs)[:7000],
            "generated_tests": "\n".join(tests)[:5000],
            "test_summary": (
                f"{report.passed}/{report.total_tests} passed, all_passed={report.all_passed}" if report else "no tests run"
            ),
            "diagnoses": [
                f"cycle {d.cycle}: {d.category.value} - {d.root_cause}" for d in state.failure_diagnoses
            ],
        }

    def judge(self, evidence: Optional[Dict[str, Any]] = None) -> JudgeVerdict:
        ev = evidence or self.collect_evidence()
        prompt = (
            f"Requirement:\n{ev['requirement']}\n\n"
            f"Acceptance criteria produced by the Planner:\n" + ("\n".join(ev["acceptance_criteria"]) or "(none)") + "\n\n"
            f"Code change (unified diff):\n```diff\n{ev['code_diff'] or '(no code change)'}\n```\n\n"
            f"Tests generated by the Test agent:\n```\n{ev['generated_tests'] or '(none)'}\n```\n\n"
            f"Objective test result: {ev['test_summary']}\n\n"
            f"Failure diagnoses: {ev['diagnoses'] or 'none'}\n\n{RUBRIC}"
        )
        response = self.invoker.invoke(prompt)
        verdict = parse_json_model(response, JudgeVerdict)
        if not ev["diagnoses"]:
            verdict.diagnosis_quality = None
        verdict.judge_model = self.model_name
        return verdict.compute_overall()
